// VestaBondTable.cs — VESTA's default bond-search table.
//
// VESTA (Momma & Izumi, J. Appl. Crystallogr. 44, 1272 (2011)) does NOT derive bond cutoffs from
// a formula or from the CIF's _geom_bond loop. When "Search bonds at start-up" is on it applies a
// fixed per-element-pair table shipped in its style.ini: for each (A1, A2) pair a min/max bond
// length, whether that pair builds coordination polyhedra (A1 = centre, A2 = vertices), and a
// line style (5 = dashed, used for O–H···O hydrogen bonds). Pairs not in the table are never
// bonded. This file is that table, transcribed verbatim from VESTA 3's style.ini.
//
// Row format: "A1 A2 min max poly style".

using System;
using System.Collections.Generic;
using System.Globalization;

public static class VestaBondTable
{
    public struct Spec
    {
        public string A1, A2;     // centre, vertex (as VESTA lists them)
        public float Min, Max;    // Å
        public bool Polyhedron;   // VESTA "show polyhedra" flag for this pair
        public bool Dashed;       // VESTA style 5 (hydrogen bond)
    }

    private static Dictionary<(string, string), Spec> _byPair;

    /// <summary>Look up VESTA's default window for an unordered element pair. Returns false if
    /// VESTA would not bond these elements at all.</summary>
    public static bool TryGet(string elemA, string elemB, out Spec spec)
    {
        EnsureParsed();
        if (_byPair.TryGetValue((elemA, elemB), out spec)) return true;
        if (_byPair.TryGetValue((elemB, elemA), out spec)) return true;
        spec = default;
        return false;
    }

    public static int Count { get { EnsureParsed(); return _byPair.Count; } }

    private static void EnsureParsed()
    {
        if (_byPair != null) return;
        var d = new Dictionary<(string, string), Spec>();
        var inv = CultureInfo.InvariantCulture;
        foreach (var row in Rows)
        {
            var f = row.Split(' ', StringSplitOptions.RemoveEmptyEntries);
            var s = new Spec
            {
                A1 = f[0], A2 = f[1],
                Min = float.Parse(f[2], inv), Max = float.Parse(f[3], inv),
                Polyhedron = f[4] == "1", Dashed = f[5] == "5",
            };
            if (s.Dashed) continue;   // H···O hydrogen bonds: not drawn (would shadow covalent O–H)
            d[(s.A1, s.A2)] = s;
        }
        _byPair = d;
    }

